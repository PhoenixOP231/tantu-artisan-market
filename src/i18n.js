export function translateUi(language, english) {
  if (language === 'en') return english;
  const pair = uiWords[english];
  const key = wordKeys[english];
  if (pair) return pair[language === 'hi' ? 0 : 1];
  if (key) return t(language, key);
  let match = typeof english === 'string' && english.match(/^Only (\d+) units are in stock\.$/);
  if (match) return language === 'hi' ? `स्टॉक में केवल ${match[1]} वस्तुएँ हैं।` : `साठ्यात फक्त ${match[1]} वस्तू आहेत.`;
  match = typeof english === 'string' && english.match(/^Request failed \((\d+)\)\.$/);
  if (match) return language === 'hi' ? `अनुरोध विफल रहा (${match[1]})।` : `विनंती अयशस्वी झाली (${match[1]}).`;
  match = typeof english === 'string' && english.match(/^(\w+) must be between (\d+) and (\d+)\.$/);
  if (match) return language === 'hi' ? `${translateUi(language, match[1])} ${match[2]} और ${match[3]} के बीच होना चाहिए।` : `${translateUi(language, match[1])} ${match[2]} आणि ${match[3]} दरम्यान असावे.`;
  return english;
}

export function translateMatchReason(language, reason) {
  if (language === 'en') return reason;
  let match = reason.match(/^Capacity for (\d+) units$/);
  if (match) return language === 'hi' ? `${match[1]} वस्तुओं की क्षमता है` : `${match[1]} वस्तूंची क्षमता आहे`;
  match = reason.match(/^Capacity is (\d+) units$/);
  if (match) return language === 'hi' ? `क्षमता ${match[1]} वस्तुएँ है` : `क्षमता ${match[1]} वस्तू आहे`;
  match = reason.match(/^(₹[\d,]+) exceeds unit budget$/);
  if (match) return language === 'hi' ? `${match[1]} प्रति वस्तु बजट से अधिक है` : `${match[1]} प्रति वस्तू बजेटपेक्षा जास्त आहे`;
  return translateUi(language, reason);
}
